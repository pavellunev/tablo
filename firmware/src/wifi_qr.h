// QR-код для подключения к точке доступа (docs/decisions.md, п.8).
//
// Кодирование — готовая библиотека ricmoo/QRCode (чистый C, без сторонних
// зависимостей): своя реализация кодов Рида-Соломона — источник тихих ошибок,
// которые нечем подтвердить без сканера на живом устройстве.
#pragma once

#include <Arduino.h>

#include <cstdint>

#include "canvas.h"

namespace wifi_qr {

// Строка стандартного формата подключения к Wi-Fi (де-факто стандарт,
// который понимают камеры iOS и Android):
//   WIFI:T:WPA;S:<ssid>;P:<password>;;
// Символы \, ;, , и " внутри ssid/password экранируются обратным слэшем —
// иначе, например, точка с запятой в SSID разорвала бы строку на поля, и
// телефон получил бы обрубленное имя сети или пароль.
String payload(const String& ssid, const String& password);

// Версия и уровень коррекции ошибок фиксированы: библиотека не подбирает их
// сама (qrcode_initText принимает версию параметром), а верхняя граница
// payload известна заранее — SSID точки доступа не длиннее 32 байт (лимит
// softAP), пароль всегда 10 символов (config::generate_ap_password). Версия 6
// (41×41 модуль) при ECC_MEDIUM вмещает 106 байт — с запасом даже если весь
// SSID состоит из экранируемых символов (32×2 + 10 + 18 служебных = 92).
constexpr uint8_t kVersion = 6;

// Сторона итогового квадрата (с рамкой) в пикселях — версия QR задаёт число
// модулей по формуле version*4+17 (см. qrcode.c), здесь вынесена в общее
// место, чтобы раскладка (layout.cpp) могла посчитать место под QR ДО вызова
// draw() и не дублировать эту арифметику у себя.
constexpr int16_t side_for(uint8_t module_px, uint8_t quiet_zone_modules) {
    return static_cast<int16_t>((kVersion * 4 + 17 + 2 * quiet_zone_modules) * module_px);
}

// Рисует QR через Canvas — тогда код появляется и в хостовом превью
// (tools/render_frame), и на панели, без второй реализации отрисовки.
// module_px — сторона одного модуля в пикселях (для читаемости с руки на
// 800×480 нужно не меньше 4-5), quiet_zone_modules — светлая рамка вокруг
// (обязательна по спецификации QR — без неё детектор камеры не находит код
// на светлом фоне). x, y — левый верхний угол ВКЛЮЧАЯ рамку.
// Возвращает сторону всего нарисованного квадрата в пикселях; 0 — text не
// поместился в kVersion (при валидных ssid/password не должно случаться, но
// молча не рисовать безопаснее, чем уронить кадр).
int16_t draw(canvas::Canvas& canvas, int16_t x, int16_t y, const String& text, uint8_t module_px,
             uint8_t quiet_zone_modules = 4);

}  // namespace wifi_qr
