// Растровые шрифты в духе формата Adafruit GFX + печать UTF-8.
//
// GFXglyph здесь — ровно то же самое, что в настоящем Adafruit_GFX
// (bitmapOffset/width/height/xAdvance/xOffset/yOffset), бит в bitmap упакован
// тем же способом (сплошной поток без выравнивания по строкам внутри одного
// глифа). Отличие — в GFXfont: вместо сплошного диапазона [first, last]
// (обязателен в стоке Adafruit_GFX, и туда пришлось бы дописывать запись на
// каждый код между ASCII и кириллицей — десятки тысяч пустых глифов) здесь
// отсортированный массив кодовых точек, параллельный массиву глифов, — по
// нему бинарный поиск. Так шрифт с ASCII + кириллицей + горсткой отдельных
// символов (▲▼→≈°·) не платит гигантским пустым диапазоном между ними.
//
// UTF-8. У Adafruit_GFX write(uint8_t) в принципе не способен адресовать
// кодовую точку выше 255 — c приходит один байт. Кириллица в UTF-8 — всегда
// два байта на символ, поэтому стандартный print() тут в принципе не мог бы
// сработать, не только «не отдаёт кириллицу». Решение — не наследоваться от
// Adafruit_GFX print(), а писать свою draw_text(): decode_utf8() разбирает
// строку на кодовые точки самостоятельно, а рисование глифа кладёт пиксели
// через canvas::Canvas напрямую, в обход текстового движка Adafruit_GFX
// целиком.
#pragma once

#include <cstdint>

#include "canvas.h"

namespace fonts {

struct GFXglyph {
    uint16_t bitmapOffset;
    uint8_t width, height;
    uint8_t xAdvance;
    int8_t xOffset, yOffset;
};

struct GFXfont {
    const uint8_t* bitmap;
    const GFXglyph* glyph;
    const uint16_t* codepoints;  // отсортировано по возрастанию, параллельно glyph[]
    uint16_t count;
    uint8_t yAdvance;  // межстрочный интервал
};

// Бинарный поиск глифа по кодовой точке. nullptr, если в шрифте такого нет —
// вызывающий код (draw_text) в этом случае символ просто пропускает: квадрат
// вместо буквы на весь текст хуже одного пропущенного символа.
const GFXglyph* find_glyph(const GFXfont& font, uint32_t codepoint);

// Разбирает один символ UTF-8, начиная с *p, продвигает указатель за него.
// Битые последовательности не роняют разбор: возвращается код замены
// U+FFFD, а указатель продвигается на один байт, чтобре не зациклиться.
uint32_t decode_utf8(const char*& p);

// Рисует UTF-8 строку, курсор — базовая линия (x, y), как в Adafruit_GFX.
// Возвращает суммарную ширину в пикселях (сумму xAdvance нарисованных
// символов) — тем же числом text_width() посчитала бы заранее.
//
// scale — целочисленный множитель (по умолчанию 1): каждый бит глифа
// рисуется блоком scale×scale вместо одного пикселя. Растровому шрифту можно
// доверить только кратное увеличение — оно не рвёт штрихи, в отличие от
// промежуточного кегля (docs/decisions.md, п.6). Так курс BTC поднят до
// зрительно доминирующего размера 48 без пятого файла шрифта: кегля 48 в
// сетке Terminus нет, а 24×2 даёт тот же результат по числу физических
// пикселей на штрих.
int16_t draw_text(canvas::Canvas& canvas, const GFXfont& font, int16_t x, int16_t y,
                   const char* utf8, canvas::Color color, uint8_t scale = 1);

// Ширина строки в пикселях без отрисовки — нужно для выравнивания по правому
// краю (проценты, цифры лимитов, дельты) и для проверки, влезает ли подпись.
int16_t text_width(const GFXfont& font, const char* utf8, uint8_t scale = 1);

}  // namespace fonts
