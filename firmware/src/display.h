// Панель: инициализация и низкоуровневая отрисовка.
//
// Частичное обновление у Waveshare 7.5" V2 есть, и пользоваться им нужно:
// полное обновление моргает всем экраном примерно на секунду. Полное всё же
// требуется периодически, иначе накапливается остаточное изображение.
#pragma once

#include <Arduino.h>

#include "config.h"
#include "layout.h"
#include "slots.h"

namespace display {

void begin();

// Тестовый кадр фазы 0: проверяем шрифт, линии и заливку на живой панели.
void show_boot_screen();

// Кадр раскладки: шапка + активный дашборд, тем же движком, что и
// tools/render_frame на хосте, — canvas_gxepd2.h оборачивает ту же панель в
// layout::draw_frame() без дублирования логики отрисовки.
void show_frame(const slots::Store& store, const layout::DeviceInfo& device,
                 const config::Dashboard& dashboard);

// Полное обновление — раз в сутки и после долгой череды частичных, чтобы
// убрать остаточное изображение.
void refresh_full();

// Имя точки доступа и её пароль (docs/decisions.md, п.8): крупно, чтобы
// читалось от стола без наклона к панели. Рисуется из главного цикла
// (main.cpp) сразу после того, как netman поднял точку доступа, — не из
// задачи веб-сервера: один объект GxEPD2 и одна шина SPI, второй писатель
// оттуда был бы гонкой с обычной перерисовкой кадра. Пока устройство сидит в
// режиме точки доступа, этот кадр и есть её единственное содержимое —
// показывать больше нечего, опрос источников в этом режиме не идёт.
void show_ap_credentials(const String& ssid, const String& password);

}  // namespace display
