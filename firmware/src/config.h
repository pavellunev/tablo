// Хранилище настроек: сети, коннекторы, ключи.
//
// Всё живёт в NVS, а не в файловой системе: NVS переживает перепрошивку и не
// лежит открытым текстом среди файлов веб-интерфейса, которые заливаются
// отдельной командой и легко утекают вместе с ними.
//
// Один владелец на запись. В предшественнике состояние писали из двух мест,
// и копия, загруженная при старте, затирала чужие поля своими устаревшими —
// сутки на поиск. Здесь любое изменение идёт через save(), читатели получают
// копию.
#pragma once

#include <Arduino.h>

#include <vector>

namespace config {

struct Network {
    String ssid;
    String password;
};

struct SlotMapping {
    String slot;    // куда положить значение
    String source;  // entity_id для Home Assistant, путь в JSON для http
    uint32_t ttl;   // сколько значение считается свежим, секунды
};

struct Connector {
    String id;
    String kind;  // "homeassistant" | "http"
    String url;
    String token;
    uint32_t interval;  // как часто опрашивать, секунды
    std::vector<SlotMapping> map;

    // Явное согласие отключить проверку сертификата для этого коннектора —
    // единственный случай, когда это оправдано: самоподписанный сертификат
    // домашнего Home Assistant. По умолчанию выключено: без этой галочки
    // Bearer-токен уходит только тем, кто прошёл проверку цепочки по
    // встроенному набору корневых сертификатов (см. docs/decisions.md, п.9).
    bool insecure = false;
};

struct Settings {
    std::vector<Network> networks;
    std::vector<Connector> connectors;
    String device_name;  // имя точки доступа и mDNS
    // Смещение от UTC в минутах: int8_t не вмещает +330 (Индия) и +480
    // (Китай) — для устройства, которое возят с собой, это не редкий край.
    int16_t timezone_minutes;

    // Пароль точки доступа (docs/decisions.md, п.8): генерируется один раз
    // при первом обращении к load() и живёт здесь же, переживая перезагрузки.
    // Секрет — как токены коннекторов, наружу через to_json(..., false) не
    // отдаётся. Менять его нельзя ничем, кроме reset() — иначе он не
    // отличался бы от прежней схемы «новый пароль на каждый подъём точки».
    String ap_password;
};

// Читает настройки из NVS. Ничего не сохранено — возвращает значения по
// умолчанию, а не пустую структуру: устройство должно подняться в режим
// настройки, а не встать.
Settings load();

// Пишет целиком. Частичной записи намеренно нет — см. про одного владельца.
bool save(const Settings&);

// Забыть всё и вернуться к заводскому состоянию (долгое удержание кнопки).
bool reset();

// Сериализация для страницы настройки. Токены наружу НЕ отдаются: страница
// показывает «задан» или пустое поле, а присланное пустое поле означает
// «оставить прежний», иначе каждое сохранение формы стирало бы ключи.
String to_json(const Settings&, bool include_secrets = false);
bool from_json(const String&, Settings&);

}  // namespace config
