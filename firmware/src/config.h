// Хранилище настроек: сети, коннекторы, ключи.
//
// Всё живёт в NVS, а не в файловой системе: NVS переживает перепрошивку и не
// лежит открытым текстом среди файлов веб-интерфейса, которые заливаются
// отдельной командой и легко утекают вместе с ними.
//
// Один владелец на запись. В предшественнике состояние писали из двух мест,
// и копия, загруженная при старте, затирала чужие поля своими устаревшими —
// сутки на поиск. Здесь любое изменение идёт через save(), читатели получают
// копию.
#pragma once

#include <Arduino.h>

#include <vector>

#include "widgets/types.h"

namespace config {

struct Network {
    String ssid;
    String password;
};

struct SlotMapping {
    String slot;    // куда положить значение
    String source;  // entity_id для Home Assistant, путь в JSON для http
    uint32_t ttl;   // сколько значение считается свежим, секунды

    // Дельта (изменение) для того же слота — второе поле того же ответа.
    // Пусто — у источника нет отдельного поля изменения (delta слота
    // остаётся 0). delta_is_previous — путь выше указывает не на готовый
    // процент изменения, а на ПРЕДЫДУЩЕЕ значение того же показателя (как
    // Valute.USD.Previous у ЦБ): дельта в этом случае считается связкой
    // (value - previous) / previous * 100, а не берётся из ответа готовой.
    // Явный флаг, а не «пустая строка означает то же самое, что готовый
    // процент» — оба смысла нужны одновременно (Binance даёт готовый
    // процент, ЦБ — только пару значений), и не выразить это одним полем
    // без потери однозначности.
    String delta_source;
    bool delta_is_previous = false;

    // История для спарклайна — из НАСТОЯЩИХ данных источника (24 часовые
    // свечи Binance, 6 часов истории Home Assistant), а не из накопления
    // редких опросов в Store (см. docs/decisions.md и Status Log про то,
    // почему это вводило в заблуждение: 5-минутный опрос давал «сутки» из
    // 40 минут реальных данных). has_history — явный флаг: этот мэппинг
    // описывает НЕ текущее значение, а массив точек истории для slot;
    // history_source — путь до самого массива (пусто — корень ответа уже
    // массив, как у Binance klines), history_item — путь ВНУТРИ каждого
    // элемента массива (пусто — элемент сам скаляр; "4" — для klines, где
    // элемент — тоже массив, и цена закрытия лежит по индексу 4).
    bool has_history = false;
    String history_source;
    String history_item;
};

struct Connector {
    String id;
    String kind;  // "homeassistant" | "http" | "anthropic" | "codex" | "imap"
    String url;
    String token;  // Bearer/access_token/пароль — смысл зависит от kind

    // OAuth-refresh для "anthropic": access_token в token живёт около восьми
    // часов, дальше API отвечает 401. refresh_token — долгоживущий, им
    // connectors.cpp получает новую пару и сохраняет её сюда же через
    // config::save() (см. connectors.cpp, poll_due, kind == "anthropic").
    // Пустая строка у прочих kind — поле им не нужно.
    String refresh_token;

    // Логин для "imap" (адрес почтового ящика) — по аналогии с token, тоже
    // секрет: сокрыт в to_json(..., false) так же, как token/refresh_token.
    String username;

    uint32_t interval;  // как часто опрашивать, секунды
    std::vector<SlotMapping> map;

    // Явное согласие отключить проверку сертификата для этого коннектора —
    // единственный случай, когда это оправдано: самоподписанный сертификат
    // домашнего Home Assistant. По умолчанию выключено: без этой галочки
    // Bearer-токен уходит только тем, кто прошёл проверку цепочки по
    // встроенному набору корневых сертификатов (см. docs/decisions.md, п.9).
    bool insecure = false;
};

// Экран, который можно собрать на странице настройки (docs/widgets.md):
// два ряда виджетов, каждый — widgets::Instance (тип, размер S/M/flex,
// опциональный разделитель слева, слот/подпись для metric/text). Переключают
// кнопками платы (buttons.h) — активный запоминается в Settings ниже.
struct Dashboard {
    String name;
    std::vector<widgets::Instance> rows[2];
};

struct Settings {
    std::vector<Network> networks;
    std::vector<Connector> connectors;
    String device_name;  // имя точки доступа и mDNS
    // Смещение от UTC в минутах: int8_t не вмещает +330 (Индия) и +480
    // (Китай) — для устройства, которое возят с собой, это не редкий край.
    int16_t timezone_minutes;

    // Пароль точки доступа (docs/decisions.md, п.8): генерируется один раз
    // при первом обращении к load() и живёт здесь же, переживая перезагрузки.
    // Секрет — как токены коннекторов, наружу через to_json(..., false) не
    // отдаётся. Менять его нельзя ничем, кроме reset() — иначе он не
    // отличался бы от прежней схемы «новый пароль на каждый подъём точки».
    String ap_password;

    // Город вместо ручного ввода координат и часового пояса (docs/
    // constructor.md, «Погода и часовой пояс»): владелец вводит одну
    // строку, коннектор kind="geocode" сам находит координаты и часовой
    // пояс приезжает вместе с погодой (utc_offset_seconds). city — то, что
    // ввёл владелец на странице настройки; city_resolved — город, для
    // которого координаты уже получены (не совпадает с city сразу после
    // правки формы — сигнал коннектору «нужно перегеокодировать»);
    // city_lat/city_lon — сами координаты. Ни одно из трёх последних полей
    // страница настройки не редактирует и не присылает — они живут только
    // здесь и в NVS, как ap_password.
    String city;
    String city_resolved;
    float city_lat = 0.0f;
    float city_lon = 0.0f;

    // Три дашборда (docs/widgets.md) — ровно три всегда, defaults() и
    // from_json это гарантируют (лишние отбрасываются, недостающие —
    // пустые), кнопки платы (buttons.h) переключают по индексу, четвёртой
    // кнопки на плате нет. active_dashboard — 0..2, вне диапазона при
    // разборе JSON откатывается к 0 (config.cpp).
    std::vector<Dashboard> dashboards;
    uint8_t active_dashboard = 0;
};

// Читает настройки из NVS. Ничего не сохранено — возвращает значения по
// умолчанию, а не пустую структуру: устройство должно подняться в режим
// настройки, а не встать.
Settings load();

// Пишет целиком. Частичной записи намеренно нет — см. про одного владельца.
bool save(const Settings&);

// Забыть всё и вернуться к заводскому состоянию (долгое удержание кнопки).
bool reset();

// Сериализация для страницы настройки. Токены наружу НЕ отдаются: страница
// показывает «задан» или пустое поле, а присланное пустое поле означает
// «оставить прежний», иначе каждое сохранение формы стирало бы ключи.
String to_json(const Settings&, bool include_secrets = false);
bool from_json(const String&, Settings&);

}  // namespace config
