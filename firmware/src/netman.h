// Подключение к Wi-Fi: перебор сохранённых сетей и точка доступа как
// запасной вариант.
//
// Осознанно не строим «список сетей с приоритетом» в духе ESPHome — там
// известный баг: с активным captive_portal устройство подключается только к
// последней сохранённой сети (esphome#13085, см. docs/decisions.md, п.4).
// Вместо приоритета при каждой попытке сканируем эфир заново и сами выбираем
// среди доступных сохранённых сетей ту, что сильнее по сигналу — так итог не
// зависит от порядка записей и от того, какая сеть была сохранена последней.
#pragma once

#include <Arduino.h>
#include <IPAddress.h>

#include <vector>

#include "config.h"

namespace netman {

enum class Mode {
    kConnecting,   // идёт первичный перебор сохранённых сетей
    kStation,      // подключены к Wi-Fi как клиент
    kAccessPoint,  // подняли свою точку, ждём настройки с телефона
};

struct ScanResult {
    String ssid;
    int32_t rssi;
    bool secure;
};

// Сканирует эфир. Одна и та же сеть, видная с нескольких точек доступа,
// схлопывается в одну запись с самым сильным сигналом; результат отсортирован
// по убыванию RSSI. Используется и для выбора сети при подключении, и для
// страницы настройки — сканирование Wi-Fi не резервируется под один сценарий.
//
// WiFi.scanNetworks() внутри освобождает результат предыдущего скана — вызов
// из двух задач одновременно (портал дёргает эту же функцию из /api/scan,
// пока try_connect_best() сканирует из главного цикла) — use-after-free.
// Функция сериализована мьютексом, так что конкурентный вызов безопасен, но
// более поздний вызывающий просто ждёт своей очереди до ~10 секунд.
std::vector<ScanResult> scan();

// То же самое, но с кешем на несколько секунд: страница настройки дёргает
// /api/scan заметно чаще, чем меняется эфир, а сам скан блокирует Wi-Fi-стек
// на время до 10 секунд — на это время веб-сервер не отвечает вообще ни на
// что, не только на /api/scan. Портал (не в этой зоне правок) стоит перевести
// на неё вместо scan() — координация описана в отчёте задачи.
std::vector<ScanResult> scan_cached();

// Пробует подключиться к сохранённым сетям settings.networks: сканирует эфир,
// выбирает лучшую по сигналу среди тех, что сохранены, и подключается. Не
// вышло за разумное время — поднимает точку доступа сама.
void begin(const config::Settings& settings);

// Периодический тик из loop(). В режиме точки доступа время от времени
// пробует вернуться в сохранённую сеть — чтобы дома устройство подключилось
// само, без похода к нему с телефоном.
void loop();

// Настройки поменялись (сохранена форма на странице настройки) — подхватить
// новый список сетей. Если в этот момент устройство сидит в режиме точки
// доступа, следующая попытка подключения будет сделана незамедлительно, а не
// по расписанию — иначе только что введённый пароль ждал бы своей очереди.
//
// Вызывается из обработчика портала, а это задача async_tcp, не главный
// цикл. Настоящее применение настроек здесь не происходит: settings уже лежат
// в NVS (portal вызывает config::save() до reload()), а reload() лишь ставит
// флаг. Сам объект настроек — тот самый vector<Connector> со String внутри,
// который параллельно перебирает try_connect_best() в главном цикле —
// главный цикл перечитает из NVS сам, в начале следующего тика loop(), когда
// его больше никто не трогает. Так одновременное чтение/присваивание одного
// вектора из двух задач не возникает вовсе, без мьютекса на сам объект.
void reload(const config::Settings& settings);

Mode mode();
String status_text();  // человекочитаемо: SSID сети или «точка доступа»
IPAddress ip();

// Имя и пароль текущей точки доступа (docs/decisions.md, п.8). Пароль
// случайный и генерируется заново при каждом её поднятии — вызывающий код
// (main.cpp) рисует их на панели сразу после смены режима на kAccessPoint.
// Вне режима точки доступа возвращают то, что осталось от последнего раза,
// — вызывать имеет смысл только когда mode() == kAccessPoint.
String ap_ssid();
String ap_password();

// Текущие настройки в рантайме — единственная копия, которую держит netman
// для попыток подключения. Остальные потребители (опрос коннекторов в
// main.cpp) читают их отсюда, а не хранят свою — второй владелец состояния
// уже стоил суток отладки в предшественнике (docs/decisions.md, п.6).
// Безопасно читать только из главной задачи (loop()), как и WiFi.status() —
// это не для вызова из обработчиков портала.
const config::Settings& settings();

}  // namespace netman
