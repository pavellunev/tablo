// Веб-интерфейс настройки: страница из LittleFS плюс JSON API.
//
// В режиме точки доступа рядом с веб-сервером поднимается DNS-заглушка,
// отвечающая своим адресом на любое имя, — это и есть captive portal:
// телефон сам предлагает открыть страницу настройки, без похода в браузер.
#pragma once

#include <Arduino.h>

namespace portal {

// Поднимает LittleFS и веб-сервер. Веб-сервер асинхронный и не блокирует
// loop(); дальше он живёт сам на фоне сетевого стека.
void begin();

// Тик DNS-заглушки. Включена, только пока netman::mode() == kAccessPoint —
// вне режима настройки нет смысла отвечать на чужие DNS-запросы.
void loop();

// Снимок состояния слотов в JSON для GET /api/status. Формируется главным
// циклом (там живёт хранилище), сюда передаётся готовой строкой и хранится
// под мьютексом: обработчик веб-сервера работает в задаче async_tcp, и
// читать std::map хранилища оттуда напрямую нельзя — main.cpp его пишет.
void set_status_json(const String& json);

}  // namespace portal
